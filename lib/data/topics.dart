/// 每日經文候選池（去重後的全部主題經文）。
List<String> dailyVersePool() {
  final seen = <String>{};
  for (final t in [...topics, ...situations]) {
    seen.addAll(t.refs);
  }
  final list = seen.toList()..sort();
  return list;
}
